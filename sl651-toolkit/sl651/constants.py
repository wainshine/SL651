def parse_def_byte(b: int) -> tuple[int, int]:
    """解析定义符：返回 (数据字节数, 小数位数)。

    高5位 = 数据字节数（0-31）
    低3位 = 小数位数（0-7）
    """
    return (b >> 3) & 0x1F, b & 0x07


